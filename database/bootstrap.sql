-- Planet Hosts bootstrap tables
-- Base tables that many application features and legacy migrations depend on but
-- which were never shipped as a migration. The migration runner executes this file
-- BEFORE any migration so both fresh installs and updates converge on the same schema.
-- All statements are idempotent (CREATE TABLE IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS api_keys (
  id INT(11) NOT NULL AUTO_INCREMENT,
  name VARCHAR(255) NOT NULL DEFAULT 'API Key',
  key_hash VARCHAR(255) NOT NULL,
  permissions VARCHAR(255) NOT NULL DEFAULT 'read',
  rate_limit INT(11) NOT NULL DEFAULT 60,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  user_id INT(11) DEFAULT NULL,
  user_type VARCHAR(20) NOT NULL DEFAULT 'admin',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_key_hash (key_hash),
  KEY idx_user (user_id, user_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

