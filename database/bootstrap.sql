CREATE TABLE IF NOT EXISTS chat_visitors (
  id INT(11) NOT NULL AUTO_INCREMENT,
  session_id VARCHAR(255) DEFAULT '',
  ip_address VARCHAR(45) DEFAULT '',
  current_page VARCHAR(500) DEFAULT '',
  timezone VARCHAR(64) DEFAULT '',
  language VARCHAR(16) DEFAULT '',
  browser VARCHAR(64) DEFAULT '',
  os VARCHAR(64) DEFAULT '',
  page_history TEXT,
  time_on_site INT(11) NOT NULL DEFAULT 0,
  first_seen DATETIME DEFAULT NULL,
  last_seen DATETIME DEFAULT NULL,
  name VARCHAR(100) DEFAULT '',
  email VARCHAR(255) DEFAULT '',
  hosting_user_id INT(11) DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_session (session_id),
  KEY idx_last_seen (last_seen)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chat_sessions (
  id INT(11) NOT NULL AUTO_INCREMENT,
  visitor_id INT(11) DEFAULT NULL,
  visitor_name VARCHAR(100) DEFAULT '',
  visitor_email VARCHAR(255) DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'waiting',
  department VARCHAR(100) DEFAULT 'General',
  subject VARCHAR(255) DEFAULT '',
  last_activity DATETIME DEFAULT NULL,
  closed_at DATETIME DEFAULT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_visitor (visitor_id),
  KEY idx_status (status),
  KEY idx_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;